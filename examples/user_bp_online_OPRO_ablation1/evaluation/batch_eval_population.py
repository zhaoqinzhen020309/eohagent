def extract_score_function(code_text):
    """从代码中提取score函数"""
    if not code_text:
        return None

    # 移除markdown标记
    code_text = re.sub(r'```python\s*\n?', '', code_text)
    code_text = re.sub(r'```\s*$', '', code_text)
    code_text = code_text.strip()

    # 查找函数定义
    lines = code_text.split('\n')
    function_lines = []
    in_function = False
    indent_level = 0

    for i, line in enumerate(lines):
        stripped = line.strip()

        # 找到函数定义
        if any(stripped.startswith(f'def {name}(') for name in ['score', 'heuristic']):
            in_function = True
            # 统一函数名为score
            if 'def heuristic(' in line:
                line = line.replace('def heuristic(', 'def score(')
            function_lines.append(line)
            indent_level = len(line) - len(line.lstrip())
            continue

        if in_function:
            # 如果是空行，保留它
            if not line.strip():
                function_lines.append(line)
                continue

            current_indent = len(line) - len(line.lstrip())

            # 函数结束检测：如果遇到非空行且缩进小于等于函数定义的缩进
            if current_indent <= indent_level:
                # 检查是否是另一个函数定义或类定义
                if (stripped.startswith('def ') or
                        stripped.startswith('class ') or
                        stripped.startswith('if __name__')):
                    break
                # 如果是同级的其他语句，也结束
                if stripped and not stripped.startswith('#'):
                    break

            function_lines.append(line)

    if function_lines:
        extracted_code = '\n'.join(function_lines)
        print(f"  提取的函数代码长度: {len(extracted_code)} 字符")
        return extracted_code
    else:
        print("  警告: 未找到函数定义，返回原始代码")
        # 如果找不到函数定义，检查是否整个代码就是一个函数
        if 'def ' in code_text:
            return code_text
        else:
            print("  错误: 代码中没有函数定义")
            return None


def load_population(json_file_path):
    """从JSON文件加载population数据"""
    try:
        with open(json_file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # 检查格式
        if 'population' in data:
            population = data.get('population', [])
            print(f"找到 {len(population)} 个个体")
        elif isinstance(data, list):
            population = data
            print(f"找到 {len(data)} 个个体（列表格式）")
        else:
            print(f"无法识别的JSON格式: {list(data.keys())}")
            return None

        # 调试：显示第一个个体的结构
        if population:
            first_individual = population[0]
            print(f"第一个个体的字段: {list(first_individual.keys())}")

            # 尝试找fitness字段
            fitness_fields = ['fitness', 'objective', 'score', 'cost']
            found_fitness = False
            for field in fitness_fields:
                if field in first_individual:
                    print(f"找到fitness字段: {field} = {first_individual[field]}")
                    found_fitness = True
                    break

            if not found_fitness:
                print("警告: 未找到常见的fitness字段")

        return population

    except Exception as e:
        print(f"读取文件失败: {e}")
        return None


def create_temp_heuristic(individual_code, temp_dir):
    """创建临时heuristic文件"""
    function_code = extract_score_function(individual_code)
    if not function_code:
        return None

    # 添加常用的导入
    header = '''# Temporary heuristic for evaluation
# Generated by batch_eval_population.py

import numpy as np
import math
import random

'''

    temp_file = os.path.join(temp_dir, 'heuristic.py')
    try:
        with open(temp_file, 'w', encoding='utf-8') as f:
            f.write(header)
            f.write(function_code)
            f.write('\n')

        # 验证文件创建成功
        if os.path.exists(temp_file):
            return temp_file
        else:
            print(f"警告: 临时文件创建失败")
            return None

    except Exception as e:
        print(f"创建临时文件时出错: {e}")
        return None


def evaluate_individual(individual_idx, individual, eva, capacity_list, size_list, temp_dir):
    """评估单个个体"""
    # 获取fitness值，更明确的方式
    fitness_value = 'N/A'
    for field in ['objective', 'fitness', 'score', 'cost']:
        if field in individual and individual[field] is not None:
            fitness_value = individual[field]
            break

    print(f"\n评估个体 {individual_idx + 1}/20 (fitness: {fitness_value})")

    # 创建临时heuristic文件
    code = individual.get('code', '')
    if not code:
        print(f"个体 {individual_idx + 1}: 没有代码")
        return []

    temp_file = create_temp_heuristic(code, temp_dir)

    if not temp_file:
        print(f"个体 {individual_idx + 1}: 无法提取代码")
        return []

    # 调试：显示生成的临时文件内容（前几行）
    try:
        with open(temp_file, 'r', encoding='utf-8') as f:
            temp_content = f.read()
            print(f"  临时文件前100字符: {temp_content[:100]}...")
    except:
        pass

    results = []

    try:
        # 添加临时目录到Python路径
        if temp_dir not in sys.path:
            sys.path.insert(0, temp_dir)

        # 重新加载heuristic模块
        if 'heuristic' in sys.modules:
            del sys.modules['heuristic']  # 完全删除而不是reload

        heuristic_module = importlib.import_module('heuristic')

        # 检查模块是否有score函数
        if not hasattr(heuristic_module, 'score'):
            print(f"  警告: 临时模块没有score函数")
            return []

        # 运行评估
        for capacity in capacity_list:
            for size in size_list:
                getdate = GetData()
                instances, lb = getdate.get_instances(capacity, size)

                for name, dataset in instances.items():
                    try:
                        avg_num_bins = -eva.evaluateGreedy(dataset, heuristic_module)
                        excess = (avg_num_bins - lb[name]) / lb[name]

                        result = {
                            'individual': individual_idx + 1,
                            'fitness': fitness_value,
                            'dataset': name,
                            'capacity': capacity,
                            'size': size,
                            'avg_bins': avg_num_bins,
                            'lower_bound': lb[name],
                            'excess_percent': 100 * excess
                        }
                        results.append(result)

                        print(f"  {name}, capacity={capacity}, size={size}: {100 * excess:.2f}%")

                    except Exception as e:
                        print(f"  评估失败 {name}: {e}")
                        continue

    except Exception as e:
        print(f"个体 {individual_idx + 1} 评估失败: {e}")
        import traceback
        traceback.print_exc()

    finally:
        # 清理临时文件
        if os.path.exists(temp_file):
            os.remove(temp_file)

        # 从路径中移除临时目录
        if temp_dir in sys.path:
            sys.path.remove(temp_dir)

        # 清理模块
        if 'heuristic' in sys.modules:
            del sys.modules['heuristic']

    return results


def main():
    parser = argparse.ArgumentParser(description='批量测试所有个体性能')
    parser.add_argument('--population-file', '--pop',
                        default='../results/pops/population_generation_20.json',
                        help='population文件路径 (默认: ../results/pops/population_generation_20.json)')
    parser.add_argument('--output', default='batch_results.csv',
                        help='输出文件名 (默认: batch_results.csv)')
    parser.add_argument('--summary', default='batch_summary.txt',
                        help='汇总文件名 (默认: batch_summary.txt)')

    args = parser.parse_args()

    print("=" * 80)
    print("批量测试最后一代所有个体")
    print("=" * 80)
    print(f"当前工作目录: {os.getcwd()}")
    print(f"Population文件: {args.population_file}")

    # 检查population文件是否存在
    if not os.path.exists(args.population_file):
        print(f"错误: 找不到population文件 {args.population_file}")
        print("请确保在evaluation文件夹下运行此脚本")
        print("可用的运行方式:")
        print("  python batch_eval_population.py")
        print("  python batch_eval_population.py --population-file ../results/pops/population_generation_20.json")
        return

    # 加载population数据
    population = load_population(args.population_file)
    if not population:
        print("加载population失败!")
        return

    # 初始化评估器
    eva = Evaluation()
    capacity_list = [100, 300, 500]
    size_list = ['1k', '5k', '10k']

    print(f"测试配置: capacity={capacity_list}, size={size_list}")

    # 创建临时目录
    with tempfile.TemporaryDirectory() as temp_dir:
        all_results = []

        # 批量评估所有个体
        for idx, individual in enumerate(population):
            individual_results = evaluate_individual(
                idx, individual, eva, capacity_list, size_list, temp_dir
            )
            all_results.extend(individual_results)

    # 保存详细结果 (CSV格式，便于分析)
    print(f"\n保存详细结果到: {args.output}")
    with open(args.output, 'w', encoding='utf-8') as f:
        f.write("Individual,Fitness,Dataset,Capacity,Size,AvgBins,LowerBound,ExcessPercent\n")
        for result in all_results:
            f.write(f"{result['individual']},{result['fitness']},{result['dataset']},"
                    f"{result['capacity']},{result['size']},{result['avg_bins']:.4f},"
                    f"{result['lower_bound']:.4f},{result['excess_percent']:.2f}\n")

    # 计算和保存汇总统计
    print(f"保存汇总统计到: {args.summary}")

    # 按个体分组计算平均性能
    individual_stats = {}
    for result in all_results:
        ind_id = result['individual']
        if ind_id not in individual_stats:
            individual_stats[ind_id] = {
                'fitness': result['fitness'],
                'excess_list': [],
                'count': 0
            }
        individual_stats[ind_id]['excess_list'].append(result['excess_percent'])
        individual_stats[ind_id]['count'] += 1

    # 计算每个个体的平均excess
    for ind_id in individual_stats:
        excess_list = individual_stats[ind_id]['excess_list']
        individual_stats[ind_id]['avg_excess'] = sum(excess_list) / len(excess_list)
        individual_stats[ind_id]['min_excess'] = min(excess_list)
        individual_stats[ind_id]['max_excess'] = max(excess_list)

    with open(args.summary, 'w', encoding='utf-8') as f:
        f.write("个体性能汇总\n")
        f.write("=" * 80 + "\n")
        f.write("Individual,Fitness,AvgExcess%,MinExcess%,MaxExcess%,TestCount\n")

        # 按平均excess排序
        sorted_individuals = sorted(individual_stats.items(),
                                    key=lambda x: x[1]['avg_excess'])

        for ind_id, stats in sorted_individuals:
            fitness_str = f"{stats['fitness']:.6f}" if isinstance(stats['fitness'], (int, float)) else str(
                stats['fitness'])
            f.write(f"{ind_id},{fitness_str},{stats['avg_excess']:.2f},"
                    f"{stats['min_excess']:.2f},{stats['max_excess']:.2f},{stats['count']}\n")

        f.write("\n" + "=" * 80 + "\n")
        f.write("总体统计:\n")
        f.write(f"测试个体数: {len(individual_stats)}\n")
        f.write(f"总测试次数: {len(all_results)}\n")

        all_excess = [r['excess_percent'] for r in all_results]
        f.write(f"整体平均excess: {sum(all_excess) / len(all_excess):.2f}%\n")
        f.write(f"最佳excess: {min(all_excess):.2f}%\n")
        f.write(f"最差excess: {max(all_excess):.2f}%\n")

    print("\n" + "=" * 80)
    print("批量测试完成!")
    print(f"详细结果: {args.output}")
    print(f"汇总统计: {args.summary}")

    # 显示前5名个体
    sorted_individuals = sorted(individual_stats.items(),
                                key=lambda x: x[1]['avg_excess'])
    print("\n前5名个体:")
    print("Rank  Individual  Fitness      AvgExcess%")
    print("-" * 45)
    for i, (ind_id, stats) in enumerate(sorted_individuals[:5]):
        fitness_str = f"{stats['fitness']:10.6f}" if isinstance(stats['fitness'],
                                                                (int, float)) else f"{str(stats['fitness']):>10s}"
        print(f"{i + 1:4d}  {ind_id:9d}  {fitness_str}  {stats['avg_excess']:8.2f}%")


if __name__ == "__main__":
    main()