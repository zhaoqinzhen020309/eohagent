#!/usr/bin/env python3
"""
从population_generation_20.json提取最佳装箱算法
"""

import json
import re
import argparse


def extract_best_from_population(json_file_path):
    """从best individual json文件中提取最佳个体"""

    try:
        with open(json_file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # 检查是否是单个个体格式
        if 'code' in data and 'objective' in data:
            # 单个最佳个体格式
            fitness = data.get('objective')
            code = data.get('code', '')
            algorithm_desc = data.get('algorithm', '')

            print(f"最佳个体fitness: {fitness}")
            print(f"算法描述: {algorithm_desc[:100]}...")
            print(f"最佳个体代码:")
            print("-" * 50)
            print(code)
            print("-" * 50)

            return code

        # 检查是否是population列表格式
        elif 'population' in data:
            population = data.get('population', [])
            if not population:
                print(f"在 {json_file_path} 中未找到population数据")
                return None

            # 找到fitness最小的个体
            best_individual = min(population, key=lambda x: x.get('fitness', float('inf')))

            fitness = best_individual.get('fitness')
            code = best_individual.get('code', '')

            print(f"最佳个体fitness: {fitness}")
            print(f"最佳个体代码:")
            print("-" * 50)
            print(code)
            print("-" * 50)

            return code

        else:
            print(f"无法识别的JSON格式: {list(data.keys())}")
            return None

    except Exception as e:
        print(f"读取文件失败: {e}")
        return None


def extract_score_function(code_text):
    """从代码中提取score函数"""

    if not code_text:
        return None

    # 移除markdown标记
    code_text = re.sub(r'```python\s*\n?', '', code_text)
    code_text = re.sub(r'```\s*$', '', code_text)

    # 查找函数定义
    lines = code_text.split('\n')
    function_lines = []
    in_function = False
    indent_level = 0

    for line in lines:
        stripped = line.strip()

        # 找到函数定义
        if any(stripped.startswith(f'def {name}(') for name in ['score', 'heuristic']):
            in_function = True
            # 统一函数名为score
            if 'def heuristic(' in line:
                line = line.replace('def heuristic(', 'def score(')
            function_lines.append(line)
            indent_level = len(line) - len(line.lstrip())
            continue

        if in_function:
            current_indent = len(line) - len(line.lstrip()) if line.strip() else indent_level + 4

            # 函数结束检测
            if line.strip() and current_indent <= indent_level:
                break

            function_lines.append(line)

    if function_lines:
        return '\n'.join(function_lines)
    else:
        print("警告: 未找到函数定义，返回原始代码")
        return code_text


def save_heuristic(code, output_file="heuristic.py"):
    """保存到heuristic.py文件"""

    header = '''# Best heuristic extracted from training results
# Generated by extract_best_heuristic.py

'''

    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(header)
        f.write(code)
        f.write('\n')

    print(f"已保存到: {output_file}")


def main():
    parser = argparse.ArgumentParser(description='从population文件提取最佳装箱算法')
    parser.add_argument('population_file',
                        help='population_generation_20.json文件路径')
    parser.add_argument('--output', default='heuristic.py',
                        help='输出文件名 (默认: heuristic.py)')

    args = parser.parse_args()

    print("=" * 60)
    print("提取最佳装箱算法")
    print("=" * 60)
    print(f"读取文件: {args.population_file}")

    # 提取最佳个体代码
    code = extract_best_from_population(args.population_file)

    if not code:
        print("提取失败!")
        return

    # 提取score函数
    function_code = extract_score_function(code)

    if not function_code:
        print("无法提取score函数!")
        return

    # 保存到文件
    save_heuristic(function_code, args.output)

    print("\n提取完成!")
    print(f"现在可以运行: python runEval.py")


if __name__ == "__main__":
    main()